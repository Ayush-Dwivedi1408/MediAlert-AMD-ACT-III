import api from "../api/client";

/**
 * SOS Mode
 * One button → sends location + health profile + critical vitals to the
 * emergency contact via the backend, which uses the WhatsApp Business API
 * first, falling back to SMS if WhatsApp delivery isn't possible. This
 * never opens the patient's own WhatsApp app — no wa.me deep link — the
 * send happens server-side through a business messaging account.
 */
export async function triggerSOS(patient) {
  // GPS is still read client-side (browser API) and passed to the backend,
  // which builds the actual alert message from the patient's real profile
  // and latest vitals.
  let latitude = null;
  let longitude = null;
  try {
    const position = await new Promise((resolve, reject) =>
      navigator.geolocation.getCurrentPosition(resolve, reject, { timeout: 5000 })
    );
    latitude = position.coords.latitude;
    longitude = position.coords.longitude;
  } catch {
    // Location unavailable — backend falls back to "please share manually"
  }

  const result = await api.patients.sendSOSAlert(patient.id, { latitude, longitude });
  return result; // { delivered_via: "whatsapp" | "sms" | null, attempts: [...], message_preview }
}

/**
 * Mental Health SOS
 * Used when a screening indicates a crisis (PHQ-9 self-harm item) or a severe
 * result (Severe Depression / Severe Anxiety). Sends a supportive, non-clinical
 * message to the patient's emergency contact -- does NOT include raw screening
 * answers, only the severity level, since those are sensitive.
 *
 * NOTE: this still uses a wa.me deep link (opens the patient's own WhatsApp),
 * unlike triggerSOS() above which now goes through the backend WhatsApp
 * Business API + SMS fallback. Only the main Emergency Card SOS button was
 * in scope for that change — let me know if you'd like this one aligned to
 * the same backend flow for consistency.
 */
export async function triggerMentalHealthSOS(patient, screeningResult) {
  const label = screeningResult.screening_type === "PHQ9" ? "depression" : "anxiety";

  let locationText = "Location unavailable";
  try {
    const position = await new Promise((resolve, reject) =>
      navigator.geolocation.getCurrentPosition(resolve, reject, { timeout: 5000 })
    );
    const { latitude, longitude } = position.coords;
    locationText = `https://maps.google.com/?q=${latitude},${longitude}`;
  } catch {
    locationText = "Could not get location — please check in by phone";
  }

  const message = `💙 MENTAL HEALTH CHECK-IN NEEDED

${patient.name} just completed a ${label} screening and the result suggests they could really use some support right now.

This isn't necessarily an emergency, but please reach out to them as soon as you can -- a call or visit would mean a lot.

📍 Location: ${locationText}

If this feels urgent:
• iCall: 9152987821
• Vandrevala Foundation: 1860-2662-345
• NIMHANS: 080-46110007

Generated by MediAlert`;

  const encodedMsg = encodeURIComponent(message);
  const phone = patient.emergency_contact_phone?.replace(/\D/g, "");

  if (phone) {
    window.open(`https://wa.me/${phone}?text=${encodedMsg}`, "_blank");
  } else {
    window.open(`https://wa.me/?text=${encodedMsg}`, "_blank");
  }

  return { success: true, location: locationText, message };
}
