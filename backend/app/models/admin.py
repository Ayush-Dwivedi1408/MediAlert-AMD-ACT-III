from sqlalchemy import Column, String, Integer, DateTime
from app.db.base import Base
from datetime import datetime


class Admin(Base):
    __tablename__ = "admins"

    id = Column(String, primary_key=True)  # e.g. AD001, AD002 — assigned in create_admin(), not autogenerated here
    name = Column(String, nullable=False)
    email = Column(String, nullable=False, unique=True)
    password_hash = Column(String, nullable=False)
    role = Column(String, nullable=False, default="admin")  # "super_admin" or "admin"
    is_active = Column(Integer, default=1)  # 0/1 — deactivated admins can't log in, but their audit trail stays intact
    mfa_secret = Column(String, nullable=True)   # base32 TOTP secret, set by /admin/mfa/setup
    mfa_enabled = Column(Integer, default=0)     # 0/1 — only true once confirmed via /admin/mfa/enable
    failed_login_attempts = Column(Integer, default=0)  # resets on any successful login
    locked_until = Column(DateTime, nullable=True)      # set once failed_login_attempts hits the cap
    created_at = Column(DateTime, default=datetime.utcnow)
    last_login_at = Column(DateTime, nullable=True)
